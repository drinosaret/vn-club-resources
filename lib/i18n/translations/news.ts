export const newsStrings: Record<Locale, TranslationDict> = { en, ja };

/** A news string in the given locale, with `{key}` placeholders filled in. */
export function ns(locale: Locale, key: keyof typeof en, vars?: Record<string, string | number>): string {
  return t(newsStrings[locale], key, vars);
}
